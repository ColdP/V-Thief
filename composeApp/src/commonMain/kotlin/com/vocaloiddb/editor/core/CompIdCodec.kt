    const val CUSTOM_DICT = "23456789ABCDEFGHKLMNPRSTWXYZ"
    fun calculate(drp: String): String {
        require(drp.length == 14) { "DRP 必须是 14 个 ASCII 字符" }
        val b = IntArray(16)
        for (i in 0 until 14 step 2) {
            val c1 = drp[i].code; val idx1 = if (c1 < ':'.code) c1 - '0'.code else c1 - 55
            val c2 = drp[i + 1].code; val idx2 = if (c2 < ':'.code) c2 - '0'.code else c2 - 55
            require(idx1 in 0..27 && idx2 in 0..27) { "DRP 只能使用数字和大写字母" }
            b[i] = TABLE_01D[idx1 * 14 + i]
            b[i + 1] = TABLE_01E[idx2 * 14 + i]
        }
        val sum = b.take(14).sum() and 255
        val high = sum ushr 4; val low = sum and 15
        shift(b, high, TABLE_1A1); shift(b, low, TABLE_4E1)
        b[14] = suffix(high); b[15] = suffix(low)
        return b.joinToString("") { it.toChar().toString() }.also { require(it.length == 16 && it.startsWith("B")) { "DevTool 生成的 CompID 不符合 B 开头规则" } }
    }
    fun drp(vendor: String, product: String, language: String, version: String): String {
        val v = vendor.trim().uppercase(); val p = product.trim().uppercase(); val l = language.trim().uppercase(); val ver = version.trim()
        require(v.length == 2 && p.length == 3 && l.length == 1 && ver in setOf("3","4","5")) { "厂商 2 位、产品 3 位、语言 1 位，版本只能是 3/4/5" }
        val out = "0${v}${l}${p}00${ver}0000"
        require(out.length == 14)
        return out
    }
    private fun shift(b: IntArray, mod: Int, table: IntArray) {
        for (i in 1 until 14) {
            val idx = CUSTOM_DICT.indexOf(b[i].toChar())
            if (idx >= 0) b[i] = CUSTOM_DICT[(idx + table[mod * 13 + i]) % 28].code
        }
    }
