private fun vvdField(content: String, key: String): String = Regex("\\\"${Regex.escape(key)}\\\"\\s*=\\s*\\\"([^\\\"]*)\\\"")
    .find(content)?.groupValues?.getOrNull(1).orEmpty()

private fun setVvdField(content: String, key: String, value: String): String {
    val regex = Regex("\\\"${Regex.escape(key)}\\\"\\s*=\\s*\\\"[^\\\"]*\\\"")
    val replacement = "\"$key\" = \"$value\""
    return if (regex.containsMatchIn(content)) regex.replaceFirst(content, replacement) else if (content.isBlank()) replacement else "$content\n$replacement"
}

