@Composable
private fun EditorRoot() {
    val repo = remember { SoundBankRepository() }
    val scope = rememberCoroutineScope()
    val defaultWorkspace = remember { "Example" }
    var workspace by remember { mutableStateOf(defaultWorkspace) }
    var files by remember { mutableStateOf(emptyList<VoicebankFile>()) }
    var samples by remember { mutableStateOf(emptyList<SampleRecord>()) }
    var ddiSummary by remember { mutableStateOf<DdiSummary?>(null) }
    var selectedDdb by remember { mutableStateOf<String?>(null) }
    var selectedDdi by remember { mutableStateOf<String?>(null) }
    var screen by remember { mutableStateOf(Screen.OVERVIEW) }
    var message by remember { mutableStateOf("就绪") }
    var phonemeFilter by remember { mutableStateOf("") }
    var oldPhoneme by remember { mutableStateOf("") }
    var newPhoneme by remember { mutableStateOf("") }
    var language by remember { mutableStateOf("CHS") }
    var voicebankName by remember { mutableStateOf("My Voicebank") }
    var salt by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<KeyBundle?>(null) }
    var xsyJson by remember { mutableStateOf("") }
    var selectedTab by remember { mutableIntStateOf(0) }

    fun refresh(path: String = workspace) {
        workspace = path
        scope.launch {
            val loadedFiles = repo.inspectWorkspace(path)
            val newDdb = loadedFiles.firstOrNull { it.type == FileType.DDB }?.path
            val newDdi = loadedFiles.firstOrNull { it.type == FileType.DDI }?.path
            files = loadedFiles
            selectedDdb = newDdb
            selectedDdi = newDdi
            samples = newDdb?.let { repo.scanSamples(it) }.orEmpty()
            ddiSummary = newDdi?.let { repo.inspectDdi(it) }
            message = "已加载 ${loadedFiles.size} 个声库文件"
        }
    }

    LaunchedEffect(Unit) { refresh() }

    Surface(Modifier.fillMaxSize(), color = MiuixTheme.colorScheme.background) {
        Column(Modifier.fillMaxSize()) {
            TopAppBar(
                title = "V-Thief",
                largeTitle = "VOCALOID 声库编辑器",
                subtitle = message,
                actions = {
                    TextButton(text = "打开工作区", onClick = { PlatformPicker.chooseDirectory(workspace)?.let(::refresh) })
                },
            )
            Row(Modifier.fillMaxSize()) {
                Rail(screen, onSelect = { screen = it })
                VerticalDivider(Modifier.fillMaxHeight(), color = MiuixTheme.colorScheme.dividerLine)
                Box(Modifier.fillMaxSize().padding(horizontal = 24.dp, vertical = 12.dp)) {
                    when (screen) {
                        Screen.OVERVIEW -> Overview(files, samples, ddiSummary, workspace, onOpen = { refresh() })
                        Screen.SAMPLES -> SamplesScreen(
                            ddbPath = selectedDdb,
                            samples = samples,
                            repo = repo,
                            onMessage = { message = it },
                            onRefresh = { selectedDdb?.let { scope.launch { samples = repo.scanSamples(it) } } },
                        )
                        Screen.PHONEMES -> PhonemesScreen(
                            summary = ddiSummary,
                            filter = phonemeFilter,
                            onFilter = { phonemeFilter = it },
                            old = oldPhoneme,
                            onOld = { oldPhoneme = it },
                            new = newPhoneme,
                            onNew = { newPhoneme = it },
                            ddiPath = selectedDdi,
                            repo = repo,
                            onMessage = { message = it },
                        )
                        Screen.IDENTITY -> IdentityScreen(
                            name = voicebankName, onName = { voicebankName = it }, language = language, onLanguage = { language = it },
                            salt = salt, onSalt = { salt = it }, bundle = generated, xsyJson = xsyJson,
                            onGenerate = {
                                val p = VoicebankProfile(voicebankName, language, ddiSummary?.phonemes?.size ?: 0, samples.size, files.sumOf { it.sizeBytes })
                                val bundle = IdentityGenerator.generate(p, ddiSummary?.phonemes.orEmpty(), salt)
                                generated = bundle
                                xsyJson = IdentityGenerator.xsyJson(bundle.xsy)
                                message = "已生成项目标识；KEY 为完整性标识，不是授权密钥"
                            },
                            onExportXsy = { PlatformPicker.chooseSaveFile("导出 XSY 配置", "xsy-profile", "json")?.let { PlatformFileBridge.writeText(it, xsyJson); message = "XSY 配置已导出" } },
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun Rail(selected: Screen, onSelect: (Screen) -> Unit) {
    Column(Modifier.width(150.dp).fillMaxHeight().padding(12.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
        Text("工作区", style = MiuixTheme.textStyles.title1)
        Screen.entries.forEach { item ->
            Button(onClick = { onSelect(item) }, modifier = Modifier.fillMaxWidth(), colors = if (item == selected) ButtonDefaults.buttonColorsPrimary() else ButtonDefaults.buttonColors()) {
                Text(when (item) { Screen.OVERVIEW -> "概览"; Screen.SAMPLES -> "采样"; Screen.PHONEMES -> "发音"; Screen.IDENTITY -> "标识 / XSY" })
            }
        }
    }
}

@Composable
private fun Overview(files: List<VoicebankFile>, samples: List<SampleRecord>, ddi: DdiSummary?, workspace: String, onOpen: () -> Unit) {
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).widthIn(max = 980.dp), verticalArrangement = Arrangement.spacedBy(16.dp)) {
        Text("声库工作区", style = MiuixTheme.textStyles.headline1)
        Text(workspace, color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
        Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
            StatCard("文件", files.size.toString(), "DDI / DDB / VVD")
            StatCard("采样", samples.size.toString(), "已识别 SND 块")
            StatCard("音素", ddi?.phonemes?.size?.toString() ?: "—", "DDI 扫描结果")
        }
        Card(Modifier.fillMaxWidth()) {
            Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("文件清单", style = MiuixTheme.textStyles.title1)
                if (files.isEmpty()) Text("没有找到声库文件，请选择包含 .ddi/.ddb/.vvd 的目录。")
                files.forEach { Text("${it.type}: ${it.name}  ·  ${formatBytes(it.sizeBytes)}") }
            }
        }
        Button(onClick = onOpen, colors = ButtonDefaults.buttonColorsPrimary()) { Text("重新扫描") }
    }
}

@Composable
private fun StatCard(title: String, value: String, caption: String) {
    Card(Modifier.width(190.dp)) { Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(5.dp)) { Text(title); Text(value, style = MiuixTheme.textStyles.headline1); Text(caption, color = MiuixTheme.colorScheme.onSurfaceVariantSummary) } }
}

@Composable
private fun SamplesScreen(ddbPath: String?, samples: List<SampleRecord>, repo: SoundBankRepository, onMessage: (String) -> Unit, onRefresh: () -> Unit) {
    var selected by remember { mutableStateOf<SampleRecord?>(null) }
    Column(Modifier.fillMaxSize(), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalAlignment = Alignment.CenterVertically) {
            Text("SND 采样", style = MiuixTheme.textStyles.headline1); Spacer(Modifier.width(8.dp))
            TextButton(text = "导出全部", enabled = ddbPath != null && samples.isNotEmpty(), onClick = { ddbPath?.let { path -> PlatformPicker.chooseDirectory()?.let { dir -> kotlinx.coroutines.MainScope().launch { repo.exportAllSamples(path, dir, samples); onMessage("已导出 ${samples.size} 个 WAV") } } } })
            TextButton(text = "刷新", onClick = onRefresh)
        }
        Text("支持标准 PCM16 WAV。替换时必须保持采样率、声道和 PCM 字节长度，以保证 DDI 偏移表有效。", color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
        LazyColumn(verticalArrangement = Arrangement.spacedBy(6.dp), contentPadding = PaddingValues(bottom = 16.dp)) {
            items(samples) { sample ->
                Card(onClick = { selected = sample }, modifier = Modifier.fillMaxWidth()) {
                    Row(Modifier.fillMaxWidth().padding(14.dp), horizontalArrangement = Arrangement.SpaceBetween) {
                        Text("#${sample.index}  0x${sample.offset.toString(16).padStart(8, '0')}")
                        Text("${sample.sampleRate} Hz · ${sample.channels} ch · ${"%.2f".format(sample.durationSeconds)} s")
                    }
                }
            }
        }
        selected?.let { sample -> SampleActions(ddbPath, sample, repo, onMessage) }
    }
}

@Composable
private fun SampleActions(ddbPath: String?, sample: SampleRecord, repo: SoundBankRepository, onMessage: (String) -> Unit) {
    Card(Modifier.fillMaxWidth()) {
        Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text("采样 #${sample.index}", style = MiuixTheme.textStyles.title1)
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                TextButton(text = "导出 WAV", onClick = { ddbPath?.let { path -> PlatformPicker.chooseSaveFile("导出采样", "sample_${sample.index}", "wav")?.let { out -> kotlinx.coroutines.MainScope().launch { repo.exportSample(path, sample, out); onMessage("采样已导出") } } } })
                TextButton(text = "替换并导出 DDB", onClick = { ddbPath?.let { path -> PlatformPicker.chooseFile("选择等长 PCM WAV", listOf("wav"))?.let { wav -> PlatformPicker.chooseSaveFile("保存 DDB", "edited", "ddb")?.let { out -> kotlinx.coroutines.MainScope().launch { runCatching { repo.replaceSample(path, sample, wav, out) }.onSuccess { onMessage("DDB 已导出") }.onFailure { onMessage(it.message ?: "替换失败") } } } } } })
            }
        }
    }
}

@Composable
private fun PhonemesScreen(summary: DdiSummary?, filter: String, onFilter: (String) -> Unit, old: String, onOld: (String) -> Unit, new: String, onNew: (String) -> Unit, ddiPath: String?, repo: SoundBankRepository, onMessage: (String) -> Unit) {
    val shown = summary?.phonemes.orEmpty().filter { filter.isBlank() || it.contains(filter, ignoreCase = true) }
    Column(Modifier.fillMaxSize(), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("发音 / 音素", style = MiuixTheme.textStyles.headline1)
        TextField(filter, onFilter, modifier = Modifier.fillMaxWidth(), label = "筛选音素", singleLine = true)
        Card(Modifier.fillMaxWidth()) {
            Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("等长发音替换", style = MiuixTheme.textStyles.title1)
                Text("为了不移动 DDI 内的偏移表，当前只允许相同 UTF-8 字节长度的替换。", color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) { TextField(old, onOld, Modifier.weight(1f), label = "旧发音", singleLine = true); TextField(new, onNew, Modifier.weight(1f), label = "新发音", singleLine = true) }
                Button(onClick = { ddiPath?.let { path -> PlatformPicker.chooseSaveFile("导出修改后的 DDI", "edited", "ddi")?.let { out -> kotlinx.coroutines.MainScope().launch { runCatching { repo.replacePhoneme(path, old, new, out) }.onSuccess { onMessage("DDI 已导出") }.onFailure { onMessage(it.message ?: "发音替换失败") } } } } }, colors = ButtonDefaults.buttonColorsPrimary()) { Text("替换并导出 DDI") }
            }
        }
        Text("可识别音素 (${shown.size})", style = MiuixTheme.textStyles.title1)
        LazyColumn(verticalArrangement = Arrangement.spacedBy(4.dp)) { items(shown) { Text(it, modifier = Modifier.fillMaxWidth().padding(8.dp)) } }
    }
}

@Composable
private fun IdentityScreen(name: String, onName: (String) -> Unit, language: String, onLanguage: (String) -> Unit, salt: String, onSalt: (String) -> Unit, bundle: KeyBundle?, xsyJson: String, onGenerate: () -> Unit, onExportXsy: () -> Unit) {
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).widthIn(max = 900.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("CompID / KEY / XSY", style = MiuixTheme.textStyles.headline1)
        Text("生成用户声库项目的确定性标识和 XSY 配置草案。KEY 仅用于完整性追踪，不是官方授权密钥。", color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) { TextField(name, onName, Modifier.weight(1f), label = "声库名称", singleLine = true); TextField(language, onLanguage, Modifier.weight(1f), label = "语言代码（如 CHS/JPN/ENG）", singleLine = true) }
        TextField(salt, onSalt, Modifier.fillMaxWidth(), label = "可选项目盐值", singleLine = true)
        Button(onClick = onGenerate, colors = ButtonDefaults.buttonColorsPrimary()) { Text("生成标识") }
        bundle?.let { bundle ->
            Card(Modifier.fillMaxWidth()) { Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) { Text("CompID: ${bundle.compId}"); Text("完整性 KEY: ${bundle.integrityKey}"); Text("XSY 参数: ${bundle.xsy.values}") } }
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) { TextButton(text = "导出 XSY JSON", onClick = onExportXsy); Text("配置草案可被版本控制和审计", color = MiuixTheme.colorScheme.onSurfaceVariantSummary) }
            Card(Modifier.fillMaxWidth()) { Text(xsyJson, modifier = Modifier.padding(16.dp)) }
        }
    }
}

private fun formatBytes(value: Long) = when { value >= 1024 * 1024 -> "%.1f MB".format(value / 1024.0 / 1024.0); value >= 1024 -> "%.1f KB".format(value / 1024.0); else -> "$value B" }



