@Composable
private fun XsyScreen(
    members: String,
    onMembers: (String) -> Unit,
    groupName: String,
    onGroupName: (String) -> Unit,
    generated: btm.m.vthief.core.XsyProfile?,
    onGenerate: () -> Unit,
    onExport: () -> Unit,
) {
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).widthIn(max = 900.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("XSY / Cross Synthesis", style = MiuixTheme.textStyles.headline1)
        Text("XSY 是 DevTool 使用的原始 Base64 字符串。把两个或更多 CompID 放入同一组；每个成员使用同一个组名生成一条 XSY 值。", color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
        TextField(groupName, onGroupName, modifier = Modifier.fillMaxWidth(), label = "XSY 组名（ASCII）", singleLine = true)
        TextField(
            value = members,
            onValueChange = onMembers,
            modifier = Modifier.fillMaxWidth(),
            label = "CompID 列表（逗号、分号或换行分隔）",
            minLines = 4,
            maxLines = 8,
        )
        Button(onClick = onGenerate, colors = ButtonDefaults.buttonColorsPrimary()) { Text("生成 XSY 值") }
        generated?.let { value ->
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                    Text("XSY 组：${value.groupName}", style = MiuixTheme.textStyles.title1)
                    Text("成员: ${value.members.joinToString()}")
                    Text(value.payload)
