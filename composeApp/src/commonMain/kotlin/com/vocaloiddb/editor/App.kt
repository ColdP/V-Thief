@Composable
private fun EditorRoot() {
    val repo = remember { SoundBankRepository() }
    val scope = rememberCoroutineScope()
    val defaultWorkspace = remember { "Example" }
    var workspace by remember { mutableStateOf(defaultWorkspace) }
    var files by remember { mutableStateOf(emptyList<VoicebankFile>()) }
    var samples by remember { mutableStateOf(emptyList<SampleRecord>()) }
    var ddiSummary by remember { mutableStateOf<DdiSummary?>(null) }
    var selectedDdb by remember { mutableStateOf<String?>(null) }
    var selectedDdi by remember { mutableStateOf<String?>(null) }
    var compId by remember { mutableStateOf<String?>(null) }
    var vvdMetadata by remember { mutableStateOf<VvdMetadata?>(null) }
    var screen by remember { mutableStateOf(Screen.OVERVIEW) }
    var message by remember { mutableStateOf("就绪") }
    var phonemeFilter by remember { mutableStateOf("") }
    var oldPhoneme by remember { mutableStateOf("") }
    var newPhoneme by remember { mutableStateOf("") }
    var vendorCode by remember { mutableStateOf("AB") }
    var productCode by remember { mutableStateOf("A20") }
    var languageCode by remember { mutableStateOf("1") }
    var versionCode by remember { mutableStateOf("4") }
    var generated by remember { mutableStateOf<KeyBundle?>(null) }
    var xsyGroupName by remember { mutableStateOf("CrossSynthesis") }
    var xsyMembers by remember { mutableStateOf("") }
    var generatedXsy by remember { mutableStateOf<btm.m.vthief.core.XsyProfile?>(null) }
    var trialEnabled by remember { mutableStateOf(false) }
    var trialExpiresOn by remember { mutableStateOf("") }
    var trialMessage by remember { mutableStateOf("") }

    fun refresh(path: String = workspace, preferredPath: String? = null) {
        workspace = path
        scope.launch {
            val loadedFiles = repo.inspectWorkspace(path)
            val newDdb = loadedFiles.firstOrNull { it.type == FileType.DDB && (preferredPath == null || it.path == preferredPath) }?.path
                ?: loadedFiles.firstOrNull { it.type == FileType.DDB }?.path
            val newDdi = loadedFiles.firstOrNull { it.type == FileType.DDI && (preferredPath == null || it.path == preferredPath) }?.path
                ?: loadedFiles.firstOrNull { it.type == FileType.DDI }?.path
            files = loadedFiles
            selectedDdb = newDdb
            selectedDdi = newDdi
            val scannedSamples = newDdb?.let { repo.scanSamples(it) }.orEmpty()
            samples = if (newDdb != null) repo.annotateSamples(newDdb, newDdi, scannedSamples) else emptyList()
            ddiSummary = newDdi?.let { repo.inspectDdi(it) }
            val resolved = repo.resolveCompId(loadedFiles)
            compId = resolved
            vvdMetadata = loadedFiles.firstOrNull { it.type == FileType.VVD }?.let { repo.inspectVvd(it.path) }
            message = "已加载 ${loadedFiles.size} 个声库文件"
        }
    }

    LaunchedEffect(Unit) { refresh() }

    Surface(Modifier.fillMaxSize(), color = MiuixTheme.colorScheme.background) {
        Column(Modifier.fillMaxSize()) {
            TopAppBar(
                title = "V-Thief",
                largeTitle = "VOCALOID 声库编辑器",
                subtitle = message,
                actions = {
                    TextButton(text = "打开 DDB / DDI", onClick = {
                        PlatformPicker.chooseFile("打开声库 DDB / DDI", listOf("ddb", "ddi"))?.let { selected ->
                            val parent = selected.substringBeforeLast('\\', selected.substringBeforeLast('/', selected))
                            refresh(parent, selected)
                        }
                    })
                },
            )
            Row(Modifier.fillMaxSize()) {
                Rail(screen, onSelect = { screen = it })
                VerticalDivider(Modifier.fillMaxHeight(), color = MiuixTheme.colorScheme.dividerLine)
                Box(Modifier.fillMaxSize().padding(horizontal = 24.dp, vertical = 12.dp)) {
                    when (screen) {
                        Screen.OVERVIEW -> Overview(files, samples, ddiSummary, workspace, compId, vvdMetadata, onOpen = {
                            PlatformPicker.chooseFile("打开声库 DDB / DDI", listOf("ddb", "ddi"))?.let { selected ->
                                val parent = selected.substringBeforeLast('\\', selected.substringBeforeLast('/', selected))
                                refresh(parent, selected)
                            }
                        })
                        Screen.SAMPLES -> SamplesScreen(
                            ddbPath = selectedDdb,
                            samples = samples,
                            repo = repo,
                            onMessage = { message = it },
                            onRefresh = { selectedDdb?.let { path -> scope.launch { val scanned = repo.scanSamples(path); samples = repo.annotateSamples(path, selectedDdi, scanned) } } },
                        )
                        Screen.PHONEMES -> PhonemesScreen(
                            summary = ddiSummary,
                            filter = phonemeFilter,
                            onFilter = { phonemeFilter = it },
                            old = oldPhoneme,
                            onOld = { oldPhoneme = it },
                            new = newPhoneme,
                            onNew = { newPhoneme = it },
                            ddiPath = selectedDdi,
                            repo = repo,
                            onMessage = { message = it },
                        )
                        Screen.IDENTITY -> IdentityScreen(
                            vendor = vendorCode, onVendor = { vendorCode = it }, product = productCode, onProduct = { productCode = it },
                            language = languageCode, onLanguage = { languageCode = it }, version = versionCode, onVersion = { versionCode = it },
                            trialExpiresOn = trialExpiresOn, bundle = generated,
                            onGenerate = {
                                runCatching { IdentityGenerator.generateFromCodes(vendorCode, productCode, languageCode, versionCode, trialExpiresOn) }
                                    .onSuccess { generated = it; compId = it.compId; message = "已生成 CompID 与对应 KEY" }
                                    .onFailure { message = it.message ?: "CompID 生成失败" }
                            },
                            onExport = { generated?.let { value -> PlatformPicker.chooseSaveFile("导出 KEY", "${value.compId}-KEY", "txt")?.let { out -> PlatformFileBridge.writeText(out, "CompID=${value.compId}\nKEY=${value.integrityKey}\nTRIAL_EXPIRES=${value.trialExpiresOn}\n"); message = "KEY 已导出" } } },
                        )
                        Screen.XSY -> XsyScreen(
                            members = xsyMembers,
                            onMembers = { xsyMembers = it },
                            generated = generatedXsy,
                            groupName = xsyGroupName,
                            onGroupName = { xsyGroupName = it },
                            onGenerate = {
                                runCatching {
                                    val ids = xsyMembers.split(',', '\n', ';').map { it.trim() }.filter { it.isNotBlank() }
                                    IdentityGenerator.generateXsy(ids, xsyGroupName)
                                }
                                    .onSuccess { value -> generatedXsy = value; message = "已生成 Cross Synthesis 组 XSY 值" }
                                    .onFailure { message = it.message ?: "XSY 生成失败" }
                            },
                            onExport = { generatedXsy?.let { value -> PlatformPicker.chooseSaveFile("导出 Cross Synthesis XSY", "cross-synthesis", "xsy")?.let { out -> PlatformFileBridge.writeText(out, value.payload); message = "XSY 原始值已导出" } } },
                        )
                        Screen.VVD -> VvdScreen(compId = compId, onMessage = { message = it })
                        Screen.SETTINGS -> SettingsScreen(
                            compId = generated?.compId ?: compId,
                            key = generated?.integrityKey,
                            trialPolicy = TrialPolicy(trialEnabled, trialExpiresOn),
                            trialMessage = trialMessage,
                            onTrialEnabled = { trialEnabled = it },
                            onTrialExpires = { value ->
                                trialExpiresOn = value
                                generated = generated?.let { IdentityGenerator.bundleFor(it.compId, value) }
                            },
                            onExport = {
                                val current = generated?.compId ?: compId ?: ""
                                val key = generated?.integrityKey ?: ""
                                val config = "{\n  \"compId\": \"$current\",\n  \"keys\": \"$key\",\n  \"trialEnabled\": $trialEnabled,\n  \"trialExpiresOn\": \"$trialExpiresOn\"\n}\n"
                                PlatformPicker.chooseSaveFile("导出 V-Thief 设置", "vthief-settings", "json")?.let { out -> PlatformFileBridge.writeText(out, config); trialMessage = "设置已导出" }
                            },
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun Rail(selected: Screen, onSelect: (Screen) -> Unit) {
    val items = listOf(
        NavigationItem("概览", MiuixIcons.Home),
        NavigationItem("采样", MiuixIcons.Music),
        NavigationItem("发音", MiuixIcons.Edit),
        NavigationItem("标识", MiuixIcons.Link),
        NavigationItem("XSY", MiuixIcons.Layers),
        NavigationItem("VVD", MiuixIcons.Tune),
        NavigationItem("设置", MiuixIcons.Settings),
    )
    val screens = Screen.entries
    val railState = rememberNavigationRailState()
    NavigationRail(
        state = railState,
        modifier = Modifier.fillMaxHeight(),
        header = { Text("V-Thief", modifier = Modifier.padding(vertical = 16.dp), style = MiuixTheme.textStyles.title1) },
    ) {
        items.forEachIndexed { index, item ->
            NavigationRailItem(
                selected = screens[index] == selected,
                onClick = { onSelect(screens[index]) },
                icon = item.icon,
                label = item.label,
            )
        }
    }
}

@Composable
private fun Overview(files: List<VoicebankFile>, samples: List<SampleRecord>, ddi: DdiSummary?, workspace: String, compId: String?, vvd: VvdMetadata?, onOpen: () -> Unit) {
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).widthIn(max = 980.dp), verticalArrangement = Arrangement.spacedBy(16.dp)) {
        Text("声库工作区", style = MiuixTheme.textStyles.headline1)
        Text(workspace, color = MiuixTheme.colorScheme.onSurfaceVariantSummary)
        Card(Modifier.fillMaxWidth()) {
            Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(5.dp)) {
                Text("CompID 声库信息", style = MiuixTheme.textStyles.title1)
                Text("CompID: ${compId ?: "未从 VVD / DDI 识别"}")
                Text("Voice Name: ${vvd?.voiceName ?: "未读取 VVD"}")
                Text("Format: ${vvd?.format ?: "—"} · Type: ${vvd?.voiceType ?: "—"}")
                if (vvd?.parameters?.isNotEmpty() == true) Text("参数: ${vvd.parameters}")
            }
        }
        Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
            StatCard("文件", files.size.toString(), "DDI / DDB / VVD")
            StatCard("采样", samples.size.toString(), "已识别 SND 块")
            StatCard("音素", ddi?.phonemes?.size?.toString() ?: "—", "DDI 扫描结果")
        }
        Card(Modifier.fillMaxWidth()) {
            Column(Modifier.padding(18.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("文件清单", style = MiuixTheme.textStyles.title1)
                if (files.isEmpty()) Text("没有找到声库文件，请选择包含 .ddi/.ddb/.vvd 的目录。")
                files.forEach { Text("${it.type}: ${it.name}  ·  ${formatBytes(it.sizeBytes)}") }
            }
        }
        Button(onClick = onOpen, colors = ButtonDefaults.buttonColorsPrimary()) { Text("重新扫描") }
    }
}

